#!/usr/bin/env python3
"""
Lumi AI Studio — Multi-Provider Real Image Engine
Supports:
  1. Google ImageFX (Imagen 3) — via Google session cookie (rohitaryal/imageFX-api)
  2. Bing Image Creator (DALL-E 3) — via Bing _U cookie (acheong08/BingImageCreator)
  3. Stability AI SD 3.5 Large — 100% Free, zero-cookie, 1024x1024 WebP
  (Completely excludes FLUX as per user directive)
"""

import os
import sys
import time
import json
import base64
import hashlib
import urllib.request
import urllib.parse
import re

MEDIA_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "generated_media"))
os.makedirs(MEDIA_DIR, exist_ok=True)


def _save_media_bytes(data: bytes, ext: str = "webp", prefix: str = "img") -> str:
    timestamp = int(time.time())
    h = hashlib.sha256(data).hexdigest()[:12]
    filename = f"{prefix}_{timestamp}_{h}.{ext}"
    filepath = os.path.join(MEDIA_DIR, filename)
    with open(filepath, "wb") as f:
        f.write(data)
    return f"/generated_media/{filename}"


def _download_and_save(url: str, ext: str = "webp", prefix: str = "img") -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = resp.read()
    return _save_media_bytes(data, ext=ext, prefix=prefix)


def generate_image_google_imagefx(prompt: str, cookie: str) -> dict:
    """
    Reverse-engineered Google ImageFX (Imagen 3) from rohitaryal/imageFX-api.
    """
    if not cookie:
        raise ValueError("Google session cookie required")

    # Step 1: Obtain session token
    sess_req = urllib.request.Request(
        "https://labs.google/fx/api/auth/session",
        headers={
            "Origin": "https://labs.google",
            "Referer": "https://labs.google/fx/tools/image-fx",
            "Cookie": cookie,
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"
        }
    )
    with urllib.request.urlopen(sess_req, timeout=15) as s_resp:
        sess_data = json.loads(s_resp.read().decode())
    
    token = sess_data.get("access_token")
    if not token:
        raise ValueError("Failed to retrieve Google ImageFX access token from session")

    # Step 2: Generate via aisandbox-pa runImageFx
    fx_payload = {
        "userInput": prompt,
        "aspectRatio": "IMAGE_ASPECT_RATIO_SQUARE",
        "numberOfImages": 1,
        "seed": 0
    }
    fx_req = urllib.request.Request(
        "https://aisandbox-pa.googleapis.com/v1:runImageFx",
        data=json.dumps(fx_payload).encode("utf-8"),
        headers={
            "Origin": "https://labs.google",
            "Referer": "https://labs.google/fx/tools/image-fx",
            "Authorization": f"Bearer {token}",
            "Cookie": cookie,
            "Content-Type": "application/json",
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64)"
        },
        method="POST"
    )
    with urllib.request.urlopen(fx_req, timeout=45) as fx_resp:
        fx_data = json.loads(fx_resp.read().decode())

    panels = fx_data.get("imagePanels", [])
    if panels and panels[0].get("generatedImages"):
        encoded = panels[0]["generatedImages"][0].get("encodedImage")
        if encoded:
            img_bytes = base64.b64decode(encoded)
            local_url = _save_media_bytes(img_bytes, ext="png", prefix="imagefx")
            return {
                "url": local_url,
                "provider": "Google ImageFX (Imagen 3)",
                "prompt": prompt
            }
    raise RuntimeError("No image generated by ImageFX")


def generate_image_bing(prompt: str, cookie: str) -> dict:
    """
    Reverse-engineered Bing Image Creator (DALL-E 3) from acheong08/BingImageCreator.
    """
    if not cookie:
        raise ValueError("Bing _U cookie required")

    u_val = cookie.strip()
    if "_U=" in u_val:
        u_val = u_val.split("_U=")[-1].split(";")[0]

    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml,application/xml;q=0.9,image/webp,*/*;q=0.8",
        "Content-Type": "application/x-www-form-urlencoded",
        "Cookie": f"_U={u_val};"
    }

    url_prompt = urllib.parse.quote(prompt)
    create_url = f"https://www.bing.com/images/create?q={url_prompt}&rt=4&FORM=GENCRE"
    payload = f"q={url_prompt}&qs=ds".encode("utf-8")

    req = urllib.request.Request(create_url, data=payload, headers=headers, method="POST")
    # Don't follow redirect automatically
    opener = urllib.request.build_opener(urllib.request.HTTPRedirectHandler())
    
    redirect_url = None
    try:
        with urllib.request.urlopen(req, timeout=25) as resp:
            redirect_url = resp.getheader("Location")
    except urllib.error.HTTPError as he:
        if he.code in (301, 302, 303, 307):
            redirect_url = he.headers.get("Location")
        else:
            raise he

    if not redirect_url:
        raise RuntimeError("Bing Image Creator failed to redirect to job queue")

    redirect_url = redirect_url.replace("&nfy=1", "")
    request_id = redirect_url.split("id=")[-1]
    polling_url = f"https://www.bing.com/images/create/async/results/{request_id}?q={url_prompt}"

    # Poll for completion
    start = time.time()
    while time.time() - start < 70:
        time.sleep(3)
        poll_req = urllib.request.Request(polling_url, headers=headers)
        with urllib.request.urlopen(poll_req, timeout=15) as poll_resp:
            html = poll_resp.read().decode("utf-8")
            if "mms.bing.com" in html or "tse" in html:
                matches = re.findall(r'src="(https://[^"]+)"', html)
                valid = [m for m in matches if "mms.bing.com" in m or "tse" in m]
                if valid:
                    first_img = valid[0].replace("&amp;", "&")
                    local_url = _download_and_save(first_img, ext="jpg", prefix="bing")
                    return {
                        "url": local_url,
                        "provider": "Bing Image Creator (DALL-E 3)",
                        "prompt": prompt
                    }
    raise TimeoutError("Bing Image Creator polling timed out")


def generate_image_sd35_large(prompt: str) -> dict:
    """
    Stability AI Stable Diffusion 3.5 Large (SD 3.5 Large).
    100% Free, zero-cookie, direct studio-grade 1024x1024 WebP.
    """
    # Attempt 1: Direct Gradio Space Call
    try:
        call_url = "https://stabilityai-stable-diffusion-3-5-large.hf.space/gradio_api/call/infer"
        payload = {
            "data": [
                prompt,
                0,
                True,
                1024,
                1024,
                28
            ]
        }
        req = urllib.request.Request(
            call_url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json", "User-Agent": "Mozilla/5.0"},
            method="POST"
        )
        with urllib.request.urlopen(req, timeout=20) as r:
            res = json.loads(r.read().decode())
            event_id = res.get("event_id")

        if event_id:
            res_url = f"https://stabilityai-stable-diffusion-3-5-large.hf.space/gradio_api/call/infer/{event_id}"
            req2 = urllib.request.Request(res_url, headers={"User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req2, timeout=60) as r2:
                for line in r2.read().decode().splitlines():
                    if line.startswith("data:"):
                        data_part = line[5:].strip()
                        parsed = json.loads(data_part)
                        if isinstance(parsed, list) and len(parsed) > 0:
                            img_obj = parsed[0]
                            if isinstance(img_obj, dict) and img_obj.get("url"):
                                remote_url = img_obj.get("url")
                                local_url = _download_and_save(remote_url, ext="webp", prefix="sd35")
                                return {
                                    "url": local_url,
                                    "remoteUrl": remote_url,
                                    "provider": "Stability AI SD 3.5 Large",
                                    "prompt": prompt
                                }
    except Exception as e:
        sys.stderr.write(f"Gradio direct SD 3.5 call failed: {e}\n")

    # Attempt 2: Via g4f.Provider.StabilityAI_SD35Large
    try:
        from g4f.client import Client
        from g4f.Provider import StabilityAI_SD35Large
        client = Client()
        res = client.images.generate(
            prompt=prompt,
            model="sd-3.5-large",
            provider=StabilityAI_SD35Large
        )
        if res and res.data and len(res.data) > 0:
            item = res.data[0]
            if getattr(item, "url", None):
                target_url = item.url
                if target_url.startswith("/media/") and "?url=" in target_url:
                    target_url = urllib.parse.unquote(target_url.split("?url=")[-1])
                local_url = _download_and_save(target_url, ext="webp", prefix="sd35")
                return {
                    "url": local_url,
                    "remoteUrl": target_url,
                    "provider": "Stability AI SD 3.5 Large",
                    "prompt": prompt
                }
            elif getattr(item, "b64_json", None):
                b64_bytes = base64.b64decode(item.b64_json)
                local_url = _save_media_bytes(b64_bytes, ext="webp", prefix="sd35")
                return {
                    "url": local_url,
                    "provider": "Stability AI SD 3.5 Large",
                    "prompt": prompt
                }
    except Exception as e:
        sys.stderr.write(f"g4f StabilityAI_SD35Large failed: {e}\n")

    raise RuntimeError("SD 3.5 Large generation failed on all upstream instances")


def generate_image_gemini_antigravity(prompt: str) -> dict:
    """
    Direct high-resolution Google Gemini Imagen 3 generation via local Antigravity/CLIProxyAPI.
    """
    req = urllib.request.Request(
        "http://127.0.0.1:8317/v1/chat/completions",
        data=json.dumps({
            "model": "gemini-3.1-flash-image",
            "messages": [{"role": "user", "content": f"draw: {prompt}"}],
            "stream": False
        }).encode("utf-8"),
        headers={
            "Content-Type": "application/json",
            "Authorization": "Bearer lumi-antigravity-local"
        },
        method="POST"
    )
    with urllib.request.urlopen(req, timeout=45) as resp:
        raw_data = json.loads(resp.read().decode())

    choices = raw_data.get("choices", [])
    if choices:
        msg = choices[0].get("message", {})
        imgs = msg.get("images")
        if imgs and isinstance(imgs, list) and len(imgs) > 0:
            img_url = imgs[0].get("image_url", {}).get("url")
            if img_url:
                if img_url.startswith("data:image/"):
                    header, b64_part = img_url.split(",", 1)
                    ext = "png"
                    if "jpeg" in header or "jpg" in header:
                        ext = "jpg"
                    elif "webp" in header:
                        ext = "webp"
                    data_bytes = base64.b64decode(b64_part)
                    local_path = _save_media_bytes(data_bytes, ext=ext, prefix="gemini")
                    return {
                        "url": local_path,
                        "remoteUrl": local_path,
                        "provider": "Google Gemini 3.1 Flash Image (Imagen 3)",
                        "prompt": prompt
                    }
                elif img_url.startswith("http"):
                    local_path = _download_and_save(img_url, ext="jpg", prefix="gemini")
                    return {
                        "url": local_path,
                        "remoteUrl": img_url,
                        "provider": "Google Gemini 3.1 Flash Image (Imagen 3)",
                        "prompt": prompt
                    }
    raise RuntimeError("No image generated by Gemini 3.1 Flash Image")


def generate_image(prompt: str, cookies: dict = None) -> dict:
    """
    Unified entry point for image generation.
    Checks authenticated Google Flow first, then Google Gemini/Antigravity, then user cookies, then SD 3.5 Large.
    """
    cookies = cookies or {}
    google_cookie = cookies.get("google") or os.environ.get("GOOGLE_COOKIE")
    bing_cookie = cookies.get("bing") or os.environ.get("BING_COOKIE")

    # 1. Google Flow (Imagen 3) — Authenticated Google Account with 994 credits
    try:
        from google_flow_engine import generate_image_google_flow, PROFILE_DIR, STORAGE_STATE_FILE
        if (PROFILE_DIR and PROFILE_DIR.exists()) or (STORAGE_STATE_FILE and STORAGE_STATE_FILE.exists()):
            res = generate_image_google_flow(prompt)
            if res and res.get("url"):
                return res
    except Exception as e:
        sys.stderr.write(f"Google Flow engine failed, falling back: {e}\n")

    # 2. Google Gemini 3.1 Flash Image (Antigravity OAuth / CLIProxyAPI on Railway)
    try:
        return generate_image_gemini_antigravity(prompt)
    except Exception as gem_err:
        sys.stderr.write(f"Google Gemini image generation failed, falling back: {gem_err}\n")

    # 3. Google ImageFX (if user provided cookie)
    if google_cookie:
        try:
            return generate_image_google_imagefx(prompt, google_cookie)
        except Exception as e:
            sys.stderr.write(f"Google ImageFX generation failed: {e}\n")

    # 4. Bing Image Creator (if user provided cookie)
    if bing_cookie:
        try:
            return generate_image_bing(prompt, bing_cookie)
        except Exception as e:
            sys.stderr.write(f"Bing Image Creator generation failed: {e}\n")

    # 5. Stability AI SD 3.5 Large (100% Free, zero auth, ultra high quality)
    try:
        return generate_image_sd35_large(prompt)
    except Exception as sd_err:
        sys.stderr.write(f"SD 3.5 Large generation failed: {sd_err}\n")

    raise RuntimeError("Image generation failed on all available AI image clusters.")
